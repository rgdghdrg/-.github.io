document.addEventListener('DOMContentLoaded', () => {
  // Год в футере
  document.getElementById('year').textContent = new Date().getFullYear();

  // Имя
  const nameEl = document.getElementById('name');
  nameEl.innerHTML = CONFIG.name + (CONFIG.name ? ' <span class="highlight">.</span>' : '');
  document.title = `${CONFIG.fullName || CONFIG.name} — Визитка`;

  // Заголовок
  document.getElementById('title').textContent = CONFIG.title;

  // Tagline
  const tagline = document.getElementById('tagline');
  if (CONFIG.tagline) {
    tagline.textContent = CONFIG.tagline;
  } else {
    tagline.style.display = 'none';
  }

  // Локация
  const locationEl = document.getElementById('location');
  if (CONFIG.location) {
    locationEl.querySelector('span').textContent = CONFIG.location;
  } else {
    locationEl.style.display = 'none';
  }

  // About
  document.getElementById('about-text').textContent = (CONFIG.about || '').trim();

  // Фото
  const avatar = document.getElementById('avatar');
  avatar.src = CONFIG.photo;
  avatar.alt = CONFIG.fullName || CONFIG.name;

  avatar.onerror = () => {
    avatar.style.display = 'none';
    const fallback = document.createElement('div');
    fallback.className = 'avatar-fallback';
    fallback.textContent = getInitials(CONFIG.name || CONFIG.fullName || '??');
    document.querySelector('.avatar-ring').prepend(fallback);
  };

  // Email
  const emailBtn = document.getElementById('email-btn');
  if (CONFIG.email) {
    emailBtn.href = `mailto:${CONFIG.email}`;
  } else {
    emailBtn.style.display = 'none';
  }

  // Passions
  const passionsContainer = document.getElementById('passions');
  passionsContainer.innerHTML = '';

  (CONFIG.passions || []).forEach(item => {
    const card = document.createElement('div');
    card.className = 'passion-card';
    card.innerHTML = `
      <div class="passion-icon">${getPassionIcon(item.icon)}</div>
      <h3>${item.title}</h3>
      <p>${item.description}</p>
    `;
    passionsContainer.appendChild(card);
  });

  // Socials
  const socialsContainer = document.getElementById('socials');
  socialsContainer.innerHTML = '';

  (CONFIG.socials || []).forEach(social => {
    const link = document.createElement('a');
    link.href = social.url;
    link.className = 'social-btn';
    link.target = '_blank';
    link.rel = 'noopener noreferrer';
    link.setAttribute('aria-label', social.name);
    link.innerHTML = `${getSocialIcon(social.icon)} <span>${social.name}</span>`;
    socialsContainer.appendChild(link);
  });
});

function getInitials(name) {
  return name
    .split(' ')
    .map(p => p[0])
    .join('')
    .toUpperCase()
    .slice(0, 2);
}

